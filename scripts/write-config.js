#!/usr/bin/env node
/* Netlify build step.
 *
 * Does two jobs, both of which can only happen at deploy time:
 *
 *   1. Writes app/config.js from the environment, so the Supabase project URL
 *      and anon key reach the browser without ever being committed.
 *   2. Stamps the build with its commit, so a live site can be asked which
 *      version it is actually running — which is the only way to tell
 *      "the deploy never happened" apart from "the browser is still caching".
 *
 * Writing a JS file rather than fetching JSON keeps the app's no-network,
 * no-build-tooling promise intact: it is one more <script> tag.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const env = process.env;
const root = path.join(__dirname, '..');

const url = (env.SUPABASE_URL || '').trim().replace(/\/+$/, '');
const key = (env.SUPABASE_ANON_KEY || '').trim();
const commit = (env.COMMIT_REF || '').slice(0, 7);
const builtAt = new Date().toISOString();

/* Which accounts backend this deployment has.
 *
 *   supabase  explicitly configured, and the better option: verified email
 *             addresses and emailed password resets.
 *   builtin   the default on Netlify. netlify/functions/api.mjs ships in this
 *             repository and needs no signup or key, so accounts work the
 *             moment the site deploys.
 *   ''        a bare checkout with no server behind it — the app runs purely
 *             locally, exactly as it always has.
 *
 * The built-in option is gated on actually being on Netlify, because the
 * functions only exist there. Guessing wrong would show a sign-in screen that
 * cannot work. */
const onNetlify = env.NETLIFY === 'true' || !!env.DEPLOY_ID;
const accounts = url ? 'supabase' : (onNetlify ? 'builtin' : '');

/* Can the built-in server send a password-reset email? Only if a mail provider
   is configured. Decided here rather than asked at runtime so the login screen
   knows before it draws which route to offer — offering a reset that can never
   arrive is worse than not offering one. */
const emailReset = accounts === 'supabase' ||
  (accounts === 'builtin' && !!(env.RESEND_API_KEY || '').trim() && !!(env.MAIL_FROM || '').trim());

/* A misconfiguration here would look, in the browser, like accounts silently
   not working — so fail the build loudly instead. */
if (url && !/^https:\/\/[\w-]+\.supabase\.(co|in)$/.test(url)) {
  console.error(`✗ SUPABASE_URL does not look like a Supabase project URL: ${url}`);
  console.error('  Expected something like https://abcdefghijklm.supabase.co');
  process.exit(1);
}
if (url && !key) {
  console.error('✗ SUPABASE_URL is set but SUPABASE_ANON_KEY is missing.');
  process.exit(1);
}
if (key && !url) {
  console.error('✗ SUPABASE_ANON_KEY is set but SUPABASE_URL is missing.');
  process.exit(1);
}
/* The service_role key bypasses Row Level Security. In a browser it would hand
   every visitor every other student's data. */
if (key && /service_role/.test(Buffer.from(key.split('.')[1] || '', 'base64').toString('utf8'))) {
  console.error('✗ SUPABASE_ANON_KEY looks like a service_role key. Do not ship that to browsers —');
  console.error('  it bypasses Row Level Security. Use the anon / public key instead.');
  process.exit(1);
}

if (accounts === 'builtin') {
  const hasKey = !!(env.RESEND_API_KEY || '').trim();
  const hasFrom = !!(env.MAIL_FROM || '').trim();
  if (hasKey !== hasFrom) {
    console.error(`✗ Email reset needs BOTH RESEND_API_KEY and MAIL_FROM. ${hasKey ? 'MAIL_FROM' : 'RESEND_API_KEY'} is missing.`);
    console.error('  Set the other one, or remove both to fall back to recovery codes.');
    process.exit(1);
  }
  if (hasFrom && !/<[^@\s]+@[^@\s]+\.[^@\s>]+>|^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(env.MAIL_FROM.trim())) {
    console.error(`✗ MAIL_FROM does not contain a usable address: ${env.MAIL_FROM}`);
    console.error('  Expected "StudyFlow <noreply@yourdomain.com>" or "noreply@yourdomain.com".');
    process.exit(1);
  }
}

const banner = `/* Generated by scripts/write-config.js at build time. Do not edit by hand —
   edit the environment variables in Netlify instead. */\n`;

const body = `window.SF_CONFIG = ${JSON.stringify({
  accounts: accounts,
  emailReset: emailReset,
  supabaseUrl: url,
  supabaseAnonKey: key,
  commit: commit,
  builtAt: builtAt
}, null, 2)};\n`;

fs.writeFileSync(path.join(root, 'app', 'config.js'), banner + body);

/* Stamp the commit into the service worker's cache name.
 *
 * This is the fix for a whole class of "the update is live but nobody can see
 * it" bugs. Bumping CACHE by hand was load-bearing and easy to forget: forget
 * it and the old cache survives activate, so the precached copy of a changed
 * file keeps being served. Deriving the name from the commit means every
 * deploy is automatically a new cache, the previous one is deleted on activate,
 * and the new build is live on the next load rather than the one after.
 *
 * It also changes sw.js itself on every deploy, which is what makes the
 * browser install a new worker at all — and therefore what makes the app able
 * to say "a newer version is ready".
 */
if (commit) {
  const swPath = path.join(root, 'sw.js');
  const sw = fs.readFileSync(swPath, 'utf8');
  const stamped = sw.replace(/^var CACHE = '([^']+)';$/m, `var CACHE = '$1-${commit}';`);
  if (stamped === sw) {
    console.error('✗ could not find the CACHE declaration in sw.js — refusing to deploy a');
    console.error('  service worker whose cache name is not tied to this commit.');
    process.exit(1);
  }
  fs.writeFileSync(swPath, stamped);
}

/* ---------------------------------------------------------------------------
 * Security headers
 * ---------------------------------------------------------------------------
 * Written here rather than in netlify.toml because one of them has to name the
 * account backend exactly, and only the build knows which one is in use.
 *
 * The Content-Security-Policy is the one that earns its place. The session
 * token lives in localStorage — unavoidable for a site with no backend of its
 * own to set an httpOnly cookie — so injected script could read it. There is
 * no 'unsafe-inline' for scripts here, which is what makes that hard: every
 * script on the page is a file from this origin, so there is nowhere for
 * injected markup to execute.
 *
 * style-src does allow 'unsafe-inline', because the app sets widths on
 * progress bars and meters through the style attribute. That is a far smaller
 * concession than the script one and does not help an attacker run code.
 */
const connect = ["'self'"];
if (url) connect.push(url);          // the Supabase project, exactly

const csp = [
  "default-src 'self'",
  "script-src 'self'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data:",
  "font-src 'self'",
  `connect-src ${connect.join(' ')}`,
  "manifest-src 'self'",
  "worker-src 'self'",
  // Nothing on this site posts a form anywhere, and nothing embeds anything.
  "form-action 'self'",
  "frame-ancestors 'self'",
  "frame-src 'none'",
  "object-src 'none'",
  "base-uri 'self'",
  'upgrade-insecure-requests'
].join('; ');

/* Only the headers netlify.toml does not already set, so nothing is sent
   twice: Referrer-Policy, X-Content-Type-Options and the rest live there. */
fs.writeFileSync(path.join(root, '_headers'), `# Generated by scripts/write-config.js. Do not edit by hand.
# netlify.toml carries the caching, routing and baseline security headers.
# These are the ones that depend on how this particular deploy is configured.

/*
  Content-Security-Policy: ${csp}
  # Tells the browser never to try this site over plain HTTP again, so there is
  # no first request to intercept and no "Not secure" to see after visit one.
  Strict-Transport-Security: max-age=31536000
  Cross-Origin-Opener-Policy: same-origin
`);

/* Also written as JSON, so the build can be checked with a plain URL
   (/version.json) without opening the app at all. */
fs.writeFileSync(path.join(root, 'version.json'), JSON.stringify({
  commit: commit || 'unknown',
  branch: env.BRANCH || env.HEAD || 'unknown',
  context: env.CONTEXT || 'local',
  accounts: accounts || 'disabled',
  emailReset: emailReset,
  builtAt: builtAt
}, null, 2) + '\n');

console.log(`✓ config written — commit ${commit || '(none)'}, accounts: ${accounts || 'off (not on Netlify, no SUPABASE_URL)'}` +
  (accounts === 'builtin' ? `, password reset by ${emailReset ? 'EMAIL' : 'recovery code (set RESEND_API_KEY and MAIL_FROM for email)'}` : ''));
